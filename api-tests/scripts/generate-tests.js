#!/usr/bin/env node
/**
 * Explore specs and scaffold editable tests.
 *
 *   npm run gen -- --list                         every operation, grouped by service and tag
 *   npm run gen -- --list --tag store             one tag
 *   npm run gen -- --plan --op addPet             every generated case for an operation, per category
 *   npm run gen -- --tag store                    write tests/<service>/<tag>.generated.spec.js
 *   npm run gen -- --op addPet,getPetById --name pet-smoke
 *   npm run gen -- --tag pet --flow               also write a CRUD flow test per resource
 *   add --service <name> to limit to one service, --force to overwrite
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { ROOT } from '../config/paths.js';
import { getFramework } from '../src/framework.js';
import { CATEGORIES, planCategory } from '../src/scenarios/plan.js';
import { matchesOperation, refOf, successStatuses, expectationsFor } from '../src/scenarios/context.js';

const { values: args } = parseArgs({
  options: {
    tag: { type: 'string' },
    op: { type: 'string' },
    service: { type: 'string' },
    name: { type: 'string' },
    list: { type: 'boolean', default: false },
    plan: { type: 'boolean', default: false },
    flow: { type: 'boolean', default: false },
    force: { type: 'boolean', default: false },
    help: { type: 'boolean', short: 'h', default: false },
  },
});

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function testBlock(op, config) {
  const ref = refOf(op);
  const status = successStatuses(op, expectationsFor(config, op.service));
  const hasPath = op.path.includes('{');
  const lines = [
    `  test(${quote(`${op.id}: ${op.method} ${op.path}`)}, async ({ api, data${hasPath ? ', resources' : ''} }) => {`,
  ];
  lines.push(`    const { query, headers } = data.params(${quote(ref)});`);
  if (hasPath) lines.push(`    const path = await resources.pathParams(${quote(ref)}); // creates the parent resource`);
  if (op.requestBody?.schema)
    lines.push(`    const body = data.build(${quote(ref)}); // override fields: data.build(ref, { field: value })`);
  const options = [hasPath && 'path', 'query', 'headers', op.requestBody?.schema && 'body'].filter(Boolean).join(', ');
  lines.push(`    const res = await api.call(${quote(ref)}, { ${options} });`);
  lines.push(`    expect(res).toHaveStatus(${status.length === 1 ? status[0] : JSON.stringify(status)});`);
  lines.push(`    // TODO: assert business rules, e.g. expect(res.body.status).toBe('available');`);
  lines.push('  });');
  return lines.join('\n');
}

function flowBlock(group) {
  const { create, read, update, remove, idParam } = group;
  const lines = [`  test(${quote(`${group.collectionPath} lifecycle`)}, async ({ api, data, resources }) => {`];
  lines.push(`    const parent = await resources.pathParams(${quote(refOf(create))});`);
  lines.push(`    const body = data.build(${quote(refOf(create))});`);
  lines.push(`    const created = await api.call(${quote(refOf(create))}, { path: parent, body });`);
  lines.push('    expect(created.ok).toBe(true);');
  lines.push(`    const path = { ...parent, ${idParam}: created.body.id ?? created.body.${idParam} };`);
  if (read) {
    lines.push('', `    const fetched = await api.call(${quote(refOf(read))}, { path });`);
    lines.push('    expect(fetched.ok).toBe(true);');
    lines.push('    // TODO: compare the fields that matter, e.g. expect(fetched.body.name).toBe(body.name);');
  }
  if (update) {
    lines.push('', `    const changes = data.build(${quote(refOf(update))}, { id: path.${idParam} });`);
    lines.push(`    expect((await api.call(${quote(refOf(update))}, { path, body: changes })).ok).toBe(true);`);
  }
  if (remove) {
    lines.push('', `    expect((await api.call(${quote(refOf(remove))}, { path, cleanup: false })).ok).toBe(true);`);
    if (read) lines.push(`    expect(await api.call(${quote(refOf(read))}, { path })).toHaveStatus(404);`);
  }
  lines.push('  });');
  return lines.join('\n');
}

function render(title, command, ops, groups, config) {
  const blocks = [...groups.map(flowBlock), ...ops.map((op) => testBlock(op, config))];
  return `// Generated by \`${command}\`. Edit freely: it is only overwritten with --force.
// Generated suites (tests/generated) already cover positive/negative/boundary/security cases;
// use this file for business rules and flows.
import { test, expect } from '../../src/fixtures/index.js';

test.describe(${quote(title)}, () => {
${blocks.join('\n\n')}
});
`;
}

function select(registry) {
  let ops = registry.list({ service: args.service, tag: args.tag });
  if (args.op)
    ops = ops.filter((op) =>
      matchesOperation(
        op,
        args.op.split(',').map((s) => s.trim()),
      ),
    );
  return ops;
}

function printList(ops) {
  for (const [group, groupOps] of Map.groupBy(ops, (op) => `${op.service} › ${op.tags[0] ?? 'untagged'}`)) {
    console.log(`\n${group}`);
    for (const op of groupOps) {
      const flags = [op.deprecated && 'deprecated', op.requiresAuth && 'auth'].filter(Boolean).join(', ');
      console.log(`  ${op.method.padEnd(7)} ${op.path.padEnd(40)} ${op.id}${flags ? `  (${flags})` : ''}`);
    }
  }
}

function printPlan(framework, ops) {
  const wanted = new Set(ops.map(refOf));
  let total = 0;
  for (const category of Object.keys(CATEGORIES)) {
    const groups = planCategory(framework, category).filter(
      (g) => (g.op && wanted.has(refOf(g.op))) || (!g.op && ops.some((op) => op.service === g.service)),
    );
    if (!groups.length) continue;
    console.log(`\n${category}`);
    for (const g of groups) {
      console.log(`  ${g.service}:${g.opId}`);
      for (const c of g.cases) console.log(`    - ${c.title}   [${category}:${g.service}:${g.opId}:${c.id}]`);
      total += g.cases.length;
    }
  }
  console.log(
    `\n${total} generated cases. Run them: npx playwright test tests/generated --grep "${ops.map((o) => o.id).join('|')}"`,
  );
}

async function main() {
  if (args.help) {
    console.log(fs.readFileSync(new URL(import.meta.url), 'utf8').split('*/')[0]);
    return;
  }
  const framework = await getFramework();
  const { registry, config } = framework;
  const ops = select(registry);
  if (!ops.length) {
    console.error('No operations match. Try `npm run gen -- --list`.');
    process.exitCode = 1;
    return;
  }

  if (args.plan) return printPlan(framework, ops);
  if (args.list || (!args.tag && !args.op)) {
    printList(ops);
    if (!args.tag && !args.op)
      console.log('\nPass --tag <name> or --op <id,...> to scaffold tests; --plan to see generated cases.');
    return;
  }

  for (const [service, serviceOps] of Map.groupBy(ops, (op) => op.service)) {
    const name = args.name ?? args.tag ?? serviceOps[0].id;
    const file = path.join(ROOT, 'tests', service, `${slug(name)}.generated.spec.js`);
    if (fs.existsSync(file) && !args.force) {
      console.error(`${path.relative(ROOT, file)} exists; pass --force to overwrite.`);
      process.exitCode = 1;
      continue;
    }
    const groups = args.flow ? registry.resourceGroups(service).filter((g) => serviceOps.includes(g.create)) : [];
    const command = `npm run gen -- ${process.argv.slice(2).join(' ')}`;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, render(`${service} › ${name}`, command, serviceOps, groups, config));
    console.log(`Wrote ${path.relative(ROOT, file)} (${serviceOps.length + groups.length} tests)`);
  }
}

await main();
